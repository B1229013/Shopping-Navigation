"""Localization accuracy on real walk photos (e.g. ~/Downloads/測試路線1照片).

Unlike eval/fusion_sweep.py's leave-one-out on the reference photos, these photos were
never in the map, can be taken *between* nodes, and can be blocked by people — so they
measure what the user actually gets.

1. Make a labelling sheet (DINOv2's top guesses are listed only as a hint — label from
   the reference map / what you remember, not from the hint):
     python -m eval.real_photos template --photos DIR --out labels.csv [--suggest]
   Fill per photo: node_a, node_b (blank if at a node), fraction (0 = at node_a,
   1 = at node_b), condition (at_node | between | occluded | other).

2. Score every photo with the server's own perception + matchers (calls the VLM:
   a few API requests per photo):
     python -m eval.real_photos collect --photos DIR --labels labels.csv --out real.json

3. Sweep weights / policies on it exactly like the reference-photo cache:
     python -m eval.fusion_sweep sweep  --cache real.json
     python -m eval.fusion_sweep policy --cache real.json
   (the cache carries each photo's true map position, so errors are metres from where
   the photo was really taken, and `--by-condition` splits the results.)
"""
from __future__ import annotations

import argparse
import csv
import json
import os
import pickle
import sys
from pathlib import Path

import numpy as np

BACKEND = Path(__file__).resolve().parents[1]
DINO_TOPK = 10
_IMG_EXT = {".jpg", ".jpeg", ".png", ".heic"}


def _photos(folder):
    files = [p for p in Path(folder).iterdir() if p.suffix.lower() in _IMG_EXT]
    return sorted(files, key=lambda p: (len(p.stem), p.stem))


def _ref_embeddings():
    """Server-side reference DINOv2 embeddings (same HF model as server/dino_embed.py).

    dino_sidecar.pkl is generated by this repo's own build scripts and committed with it
    — a trusted file, not user input."""
    side = pickle.load(open(BACKEND / "dino_sidecar.pkl", "rb"))
    meta = json.loads((BACKEND.parent / "APPNAV_ios" / "Models" / "dino_ref_meta.json").read_text())
    names = [e["file"] for e in meta]
    emb = np.stack([np.asarray(side[n], dtype=np.float32) for n in names])
    emb /= np.linalg.norm(emb, axis=1, keepdims=True)
    return emb, np.array([e["nid"] for e in meta])


def _dino_topk(path, emb, owner):
    from server import dino_embed
    q = dino_embed.embed_image(str(path))
    if q is None:
        sys.exit("DINOv2 not available — pip install torch transformers")
    sims = emb @ q
    per_node = {}
    for j in np.argsort(-sims):
        per_node.setdefault(int(owner[j]), float(sims[j]))
        if len(per_node) >= DINO_TOPK:
            break
    return per_node


def template(args):
    rows = []
    if args.suggest:
        emb, owner = _ref_embeddings()
    for p in _photos(args.photos):
        row = {"photo": p.name, "node_a": "", "node_b": "", "fraction": "", "condition": "", "notes": ""}
        if args.suggest:
            top = list(_dino_topk(p, emb, owner).items())[:3]
            row["dino_hint"] = " ".join(f"WP{n}({s:.2f})" for n, s in top)
            print(f"{p.name:10s} {row['dino_hint']}", file=sys.stderr)
        rows.append(row)
    with open(args.out, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    print(f"wrote {len(rows)} rows → {args.out}")


def collect(args):
    from server.config import GRID_N, NEO4J_PLACE
    from server.neo4j_client import get_neo4j
    from server.photo_quality import assess_image, assess_occlusion
    from server.visual_localization import match_by_grid
    from server import server as srv
    from PIL import Image, ImageOps

    ref_map = get_neo4j().load_reference_map(NEO4J_PLACE)
    emb, owner = _ref_embeddings()
    labels = list(csv.DictReader(open(args.labels, encoding="utf-8")))
    queries = []
    for row in labels:
        if not row.get("node_a"):
            continue
        a = int(row["node_a"])
        b = int(row["node_b"]) if row.get("node_b") else None
        frac = float(row["fraction"] or 0) if b else 0.0
        pa = ref_map.photos[a]
        xy = (pa.pdr_x, pa.pdr_y)
        if b:
            pb = ref_map.photos[b]
            xy = (pa.pdr_x + frac * (pb.pdr_x - pa.pdr_x), pa.pdr_y + frac * (pb.pdr_y - pa.pdr_y))
        truth = b if (b and frac > 0.5) else a
        path = Path(args.photos) / row["photo"]

        # same preprocessing as POST /photo
        tmp = Path(args.out).with_suffix(".tmp.jpg")
        im = ImageOps.exif_transpose(Image.open(path)).convert("RGB")
        im.thumbnail((1600, 1600))
        w, h = im.size
        im.save(tmp, "JPEG", quality=85)
        quality = assess_image(str(tmp))

        perception, _ = srv._vlm_perceive_two_pass(image_path=str(tmp), goal="定位", goal_objects=[],
                                                   img_w=w, img_h=h)
        dets = [srv.PerceptionDetection(label=d.label, box=d.bbox, score=d.score) for d in perception.detections]
        occ = assess_occlusion(dets, w, h)
        items = srv._build_localization_items(dets, [], w, h)
        ocr = srv._build_ocr_items(perception.ocr_texts, w, h)
        grid = match_by_grid(items, ref_map, top_k=10, ocr_items=ocr, grid_n=GRID_N,
                             store_zone=perception.store_zone or None)
        queries.append({
            "nid": truth, "truth_xy": list(xy), "photo": row["photo"], "set": row.get("condition") or "all",
            "condition": row.get("condition") or "", "dino": {str(k): v for k, v in _dino_topk(path, emb, owner).items()},
            "grid": {str(n): s for n, s, _ in grid}, "n_items": len(items),
            "sharpness": quality.sharpness, "brightness": quality.brightness,
            "occluded_fraction": occ.fraction, "retake_hint": quality.hint or occ.hint,
        })
        print(f"{row['photo']}: truth WP{truth} | dino top {next(iter(queries[-1]['dino']))} | "
              f"grid top {next(iter(queries[-1]['grid']), None)} | {len(items)} objects", file=sys.stderr)
        tmp.unlink(missing_ok=True)

    out = {"place": ref_map.place, "grid_n": GRID_N, "dropout": 0.0, "source": "real_photos",
           "nodes": {str(n): {"x": p.pdr_x, "y": p.pdr_y, "nbrs": list(p.neighbor_nids)}
                     for n, p in ref_map.photos.items()},
           "queries": queries}
    Path(args.out).write_text(json.dumps(out, ensure_ascii=False))
    print(f"wrote {len(queries)} labelled photos → {args.out}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    t = sub.add_parser("template")
    t.add_argument("--photos", required=True)
    t.add_argument("--out", required=True)
    t.add_argument("--suggest", action="store_true", help="add DINOv2's top-3 nodes as a labelling hint")
    c = sub.add_parser("collect")
    c.add_argument("--photos", required=True)
    c.add_argument("--labels", required=True)
    c.add_argument("--out", required=True)
    args = ap.parse_args()
    {"template": template, "collect": collect}[args.cmd](args)


if __name__ == "__main__":
    main()
